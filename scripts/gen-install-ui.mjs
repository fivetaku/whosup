#!/usr/bin/env node
// install.sh carries the screen helpers of src/tui.mjs (the block between its two UI_JS marker lines) in a single-quoted shell
// variable, UI_JS: it asks its questions before whosup's files are on the machine. This writes that copy into install.sh
// between its own marker lines. test/tui.test.mjs fails when the two differ — run this after changing src/tui.mjs:
//   node scripts/gen-install-ui.mjs           write install.sh
//   node scripts/gen-install-ui.mjs --check   only say whether install.sh is up to date (exit 1 when it is not)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { uiJsBlock } from '../src/tui.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
export const INSTALL_START = '# >>> UI_JS generated by scripts/gen-install-ui.mjs from src/tui.mjs: do not edit here'
export const INSTALL_END = '# <<< UI_JS'

// the lines install.sh should have between (and including) its marker lines
export function installUiSection(tuiSource) {
  const block = uiJsBlock(tuiSource)
  if (block.includes("'")) throw new Error('src/tui.mjs: the UI_JS block has a single quote in it (it would end the shell string)')
  return `${INSTALL_START}\nUI_JS='\n${block}uiCli(process.argv.slice(1))\n'\n${INSTALL_END}`
}
// install.sh with that section put in place of what is there now
export function withUiSection(installSource, tuiSource) {
  const a = installSource.indexOf(INSTALL_START), b = installSource.indexOf(INSTALL_END)
  if (a < 0 || b < a) throw new Error('install.sh: no UI_JS marker lines')
  return installSource.slice(0, a) + installUiSection(tuiSource) + installSource.slice(b + INSTALL_END.length)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const install = `${ROOT}install.sh`, tui = `${ROOT}src/tui.mjs`
  const now = readFileSync(install, 'utf8'), next = withUiSection(now, readFileSync(tui, 'utf8'))
  if (process.argv.includes('--check')) {
    if (now !== next) { console.error('install.sh: the UI_JS copy differs from src/tui.mjs (run: node scripts/gen-install-ui.mjs)'); process.exitCode = 1 }
  } else if (now !== next) { writeFileSync(install, next); console.log('install.sh: UI_JS written') }
  else console.log('install.sh: UI_JS is up to date')
}
